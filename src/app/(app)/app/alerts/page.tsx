import type { Metadata } from "next";

import { MetricTile, PageSection, PageShell } from "@/components/app/page-shell";
import { AlertsQueue } from "@/components/dashboard/alerts-queue";
import { RISK_COLORS, type RiskLevel } from "@/config/risk";
import { requireOrganization } from "@/lib/auth";
import { listAlerts, SAVED_VIEWS, type SavedViewId } from "@/lib/data/alerts";

export const metadata: Metadata = { title: "Alerts" };

export default async function AlertsPage({
  searchParams,
}: {
  searchParams: Promise<{ view?: string; status?: string; severity?: string }>;
}) {
  const params = await searchParams;
  const view = (SAVED_VIEWS.find((item) => item.id === params.view)?.id ?? "all") as SavedViewId;
  const { supabase, user, organization } = await requireOrganization();

  const rows = await listAlerts(supabase, organization!.id, {
    view,
    userId: user.id,
    ...(params.status ? { status: params.status } : {}),
    ...(params.severity ? { severity: params.severity } : {}),
  });

  const critical = rows.filter((row) => row.severity === "critical").length;
  const unassigned = rows.filter((row) => !row.assigneeName).length;
  const now = Date.now();
  const breached = rows.filter((row) => row.dueAt !== null && new Date(row.dueAt).getTime() < now).length;
  const severityCounts: Record<RiskLevel, number> = { critical: 0, high: 0, medium: 0, low: 0 };
  for (const row of rows) severityCounts[row.severity] += 1;
  const highPlus = severityCounts.critical + severityCounts.high;
  const severities: RiskLevel[] = ["critical", "high", "medium", "low"];

  return (
    <PageShell
      eyebrow="Operations / Triage"
      title="Alerts"
      description="Every alert is generated by the rules engine at ingestion and ordered by severity. SLA clocks start when the alert is created."
      meta={
        <>
          <span className="num">{rows.length} in view</span>
          <span className={critical > 0 ? "num text-risk-critical" : "num"}>{critical} critical</span>
          <span className="num">{unassigned} unassigned</span>
          <span className={breached > 0 ? "num text-risk-medium" : "num"}>{breached} past SLA</span>
        </>
      }
    >
      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <MetricTile
          label="Alerts in view"
          value={rows.length.toLocaleString("en-US")}
          hint="across the active saved view and filters"
        />
        <MetricTile
          label="Critical or high"
          value={highPlus.toLocaleString("en-US")}
          tone={highPlus > 0 ? "critical" : "positive"}
          hint={`${critical} critical · ${severityCounts.high} high`}
        />
        <MetricTile
          label="Unassigned"
          value={unassigned.toLocaleString("en-US")}
          tone={unassigned > 0 ? "warning" : "positive"}
          hint="waiting for an analyst to pick them up"
        />
        <MetricTile
          label="Past SLA"
          value={breached.toLocaleString("en-US")}
          tone={breached > 0 ? "critical" : "positive"}
          hint="due time already passed"
        />
      </div>

      <PageSection
        id="severity-mix-heading"
        title="Severity mix in view"
        description="Critical alerts carry a 4-hour SLA, high 12 hours, medium 24 and low 48"
      >
        <div className="flex h-3 w-full overflow-hidden rounded-full bg-muted" role="img" aria-label="Severity split for the alerts in view">
          {severities.map((severity) =>
            severityCounts[severity] > 0 ? (
              <span
                key={severity}
                style={{
                  width: `${(severityCounts[severity] / Math.max(1, rows.length)) * 100}%`,
                  background: RISK_COLORS[severity],
                }}
                title={`${severity}: ${severityCounts[severity]}`}
              />
            ) : null,
          )}
        </div>
        <ul className="mt-4 grid gap-3 sm:grid-cols-4">
          {severities.map((severity) => (
            <li key={severity} className="flex items-center gap-2.5">
              <span className="size-2.5 rounded-sm" style={{ background: RISK_COLORS[severity] }} aria-hidden="true" />
              <span className="flex-1 text-[12px] capitalize text-muted-foreground">{severity}</span>
              <span className="num text-[12.5px] font-medium">{severityCounts[severity]}</span>
              <span className="num w-12 text-right text-[11px] text-muted-foreground">
                {((severityCounts[severity] / Math.max(1, rows.length)) * 100).toFixed(1)}%
              </span>
            </li>
          ))}
        </ul>
      </PageSection>

      <AlertsQueue rows={rows} view={view} status={params.status ?? ""} severity={params.severity ?? ""} />
    </PageShell>
  );
}
